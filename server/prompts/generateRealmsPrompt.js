export function buildGenerateRealmsPrompt({ lessonTitle, studentLevel, lessonText, storyTheme, memory }) {
  return `
أنت مصمم ألعاب تعليمية وتفاعلية باللغة العربية مخصص لمنصة "حُرّاس المعرفة - بوابة الأكوان".
المطلوب تحليل نص الدرس المستهدف وتطوير 4 إلى 5 أسئلة خيارات متعددة مخصصة للتحديات الأركيدية (متاهة المعرفة، جزر السماء، سباق المجرات، حارس النجوم).

بيانات الدرس المستهدف:
- عنوان الدرس: ${lessonTitle}
- المستوى التعليمي / العمر: ${studentLevel}
- الطابع القصصي: ${storyTheme || 'مدينة مستقبلية'}
- نص الدرس التفصيلي:
${lessonText}

${memory && memory.struggleAreas && memory.struggleAreas.length > 0
  ? `ملاحظة تكيفية من الذاكرة: الطالب يواجه صعوبة سابقة في المفاهيم التالية: ${memory.struggleAreas.join(', ')}. يرجى التركيز عليها بأسئلة وتوضيحات مبسطة.`
  : ''}

يجب أن تكون الاستجابة الصادرة منك عبارة عن كائن JSON فقط (Strict Valid JSON Object) وبدون أي نصوص أو مقدمات أو شرح خارجي بالصيغة الهيكلية التالية بالضبط:

{
  "title": "عنوان مشوق للمهمة بالأكوان المعرفية باللغة العربية",
  "intro": "مقدمة قصيرة ومحفزة للمهمة باللغة العربية (سطران إلى 3 أسطر)",
  "questions": [
    {
      "id": "q1",
      "type": "multiple_choice",
      "question": "نص السؤال العلمي باللغة العربية المرتكز على مفاهيم الدرس",
      "choices": [
        { "id": "a", "text": "الخيار الأول" },
        { "id": "b", "text": "الخيار الثاني" },
        { "id": "c", "text": "الخيار الثالث" },
        { "id": "d", "text": "الخيار الرابع" }
      ],
      "correctChoiceId": "a",
      "explanation": "تفسير عليل وشرح موجز ودقيق باللغة العربية للإجابة الصحيحة",
      "difficulty": 1
    }
  ]
}

قواعد واشتراطات السرد القصصي والتحدي:
1. "title": عنوان أركيدي بطل وحماسي يجمع بين موضوع الدرس والسمة القصصية (${storyTheme}).
2. "intro": قصة قصيرة مشوقة ومحبوكة من أسطر (2-3 أسطر) تصف مهمة بطل الأكوان ("حارس النور") في عالم (${storyTheme}) لحماية واستعادة مفاهيم درس (${lessonTitle})، بدون عبارات طفولية مبتذلة أو تكلف.
3. الأسئلة والتوضيحات: يجب إرجاع 4 خيارات (a, b, c, d) لكل سؤال، والتزام الدقة العلمية التامة المستمدة من الدرس.
4. التزم باللغة العربية الفصحى المعاصرة والأنيقة المناسبة لسن الطالب (${studentLevel}).
5. يمنع منعاً باتاً استخدام علامات تنصيص غير مهرّبة داخل قيم النصوص.
`;
}

